const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const {boot,HISTORY,getNow}=require('./timer-fixture.cjs');
const entry=(id,task='Original')=>({id,task,taskId:null,seconds:1500,endedAt:getNow(),day:'2026-10-24'});
const storage=()=>({[HISTORY]:JSON.stringify({version:1,baselineSeconds:600,entries:[entry('old'),entry('other')]})});
let store=storage(), app=boot(store);
app.run("taskQueue=[{id:'study',name:'Study',done:false,dailyTarget:2}]");
assert(app.run("changeSessionHistory('edit','old','Study','study').ok"));
assert.equal(app.run("focusHistory.entries[0].taskId"),'study');
assert.equal(app.run('focusHistory.entries[0].seconds'),1500);
assert.equal(app.run('focusHistory.entries[0].endedAt'),getNow());
assert(app.run("changeSessionHistory('delete','old').ok"));
assert.equal(app.run('focusHistory.entries.length'),1);
assert.equal(app.get('weeklySessions').textContent,'1');
app=boot(store);
assert(app.run("changeSessionHistory('undo').ok"));
assert.equal(app.run('focusHistory.entries[0].task'),'Study');
// A subsequent completion is retained when undoing an earlier edit.
app.run("recordFocusedSession(1500,'fresh',Date.now())");
assert(app.run("changeSessionHistory('undo').ok"));
assert.equal(app.run('focusHistory.entries[0].task'),'Original');
assert.equal(app.run('focusHistory.entries.length'),3);
assert.equal(app.run('focusHistory.baselineSeconds'),600);
assert(app.run("changeSessionHistory('delete','old').ok"));
app.run("recordFocusedSession(1500,'old',Date.now())");
assert.equal(app.run("focusHistory.entries.filter(e=>e.id==='old').length"),0);
const before=JSON.stringify(app.run('focusHistory'));
app.c.localStorage.setItem=()=>{throw Error('full')};
assert(!app.run("changeSessionHistory('edit','other','New label').ok"));
assert.equal(JSON.stringify(app.run('focusHistory')),before);
app=boot(storage());
app.run('completionPending=true');
assert(!app.run("changeSessionHistory('delete','old').ok"));
app.run('completionPending=false; handleDialPress()');
const deadline=app.run('timerDeadline');
assert(app.run("changeSessionHistory('edit','old','Correction').ok"));
assert.equal(app.run('timerDeadline'),deadline); assert(app.run('isRunning'));
for(let i=0;i<25;i++)app.run(`changeSessionHistory('edit','old','Correction ${i}')`);
assert.equal(app.run('focusHistory.undo.length'),20);
assert.equal(app.run("validHistory({version:1,baselineSeconds:0,entries:[],undo:[{}]})"),null);
// Exercise UI actions, date filtering, keyboard form submission and focus restoration.
app=boot(storage());
vm.runInContext(fs.readFileSync(__dirname+'/../history-editor.js','utf8'),app.c);
app.get('openSessionHistory').fire('click');
assert(app.get('sessionHistoryDialog').open);
assert.equal(app.get('sessionHistoryList').children.length,2);
app.get('sessionHistoryList').children[0].children[2].children[0].fire('click');
assert(!app.get('sessionHistoryEditForm').hidden);
app.get('sessionHistoryTask').value='Corrected';
app.get('sessionHistoryEditForm').fire('submit',{preventDefault(){}});
assert.equal(app.run('focusHistory.entries[0].task'),'Corrected');
app.get('sessionHistoryList').children[0].children[2].children[1].fire('click');
assert.equal(app.run('focusHistory.entries.length'),1);
app.get('undoSessionHistory').fire('click');
assert.equal(app.run('focusHistory.entries.length'),2);
app.get('sessionHistoryDate').value='2020-01-01';app.get('sessionHistoryDate').fire('change');
assert.equal(app.get('sessionHistoryList').children[0].textContent,'No sessions for this date.');
app.get('allSessionHistory').fire('click');assert.equal(app.get('sessionHistoryList').children.length,2);
app.get('closeSessionHistory').fire('click');
assert.equal(app.c.document.activeElement,app.get('openSessionHistory'));
const html=fs.readFileSync(__dirname+'/../index.html','utf8');
for(const id of ['sessionHistoryDialog','sessionHistoryDate','sessionHistoryTask','sessionHistoryQueue','openSessionHistory'])assert(html.includes(`id="${id}"`));
console.log('History editing: relabel/link, delete, durable Undo, derived stats, stale recovery, failed saves, active timer, UI and date filter passed.');
